import { z } from 'zod';
import { parseConfig } from '../config.js';
import type { Personality } from '../config.js';

const key = z.string().min(1).max(1024);
const id = z.string().regex(/^[1-9][0-9]{0,31}$/);
const count = z.number().int().safe().nonnegative();
const positive = count.positive();
const timestamp = count;
const eventTimestamp = z.number().int().safe().min(-8_640_000_000_000_000).max(8_640_000_000_000_000);
const hash = z.string().regex(/^[a-f0-9]{64}$/);
export const sourceRefSchema = z.object({ sourceId: key, sourceEpoch: positive }).strict();
export const dependencySchema = z.object({ memoryId: key, version: positive }).strict();
export const provenanceSchema = z.object({
  complete: z.literal(true),
  sourceRefs: z.array(sourceRefSchema).min(1).max(1000),
  messageKeys: z.array(key).min(1).max(10000),
  dependencyVersions: z.array(dependencySchema).max(10000),
}).strict();
export type SourceRef = z.infer<typeof sourceRefSchema>;
export type DependencyVersion = z.infer<typeof dependencySchema>;
export type Provenance = z.infer<typeof provenanceSchema>;

export const sourceSchema = z.object({
  sourceId: key, botId: id, personalityId: key,
  conversationType: z.enum(['group', 'private']), conversationId: id,
  sourceEpoch: positive, allowed: z.boolean(), forgotten: z.boolean(),
}).strict();
export type SourceRecord = z.infer<typeof sourceSchema>;

const routeSchema = z.object({
  provider: key, model: key, reasoningEffort: key.optional(),
  maxOutputTokens: positive.max(131072), timeoutMs: positive.max(300000),
}).strict();
const personalitySchema = z.unknown().transform((value, ctx): Personality => {
  try {
    if (!value || typeof value !== 'object' || !('id' in value) || typeof value.id !== 'string') throw new Error();
    const config = parseConfig({ personalities: [value], bindings: { defaultPersonalityId: value.id },
      security: { confirmSharedPrivateToGroups: true } });
    return config.personalities[0]!;
  } catch {
    ctx.addIssue({ code: 'custom', message: 'invalid persisted personality' });
    return z.NEVER;
  }
});
export const snapshotSchema = z.object({
  id: key, personality: personalitySchema,
  routes: z.object({ router: routeSchema, recall: routeSchema, reflect: routeSchema, retain: routeSchema, reply: routeSchema }).strict(),
  budgets: z.unknown().transform((value, ctx) => {
    try { return parseConfig({ budgets: value }).budgets; }
    catch { ctx.addIssue({ code: 'custom', message: 'invalid persisted budgets' }); return z.NEVER; }
  }),
  memory: z.unknown().transform((value, ctx) => {
    try { return parseConfig({ memory: value }).memory; }
    catch { ctx.addIssue({ code: 'custom', message: 'invalid persisted memory config' }); return z.NEVER; }
  }),
  configRevision: key, promptVersion: key, createdAt: timestamp,
}).strict();

export const messageSchema = z.object({
  key, botId: id, personalityId: key, conversationType: z.enum(['group', 'private']), conversationId: id,
  messageId: key, sourceRef: sourceRefSchema,
  author: z.discriminatedUnion('kind', [
    z.object({ kind: z.literal('qq'), qqId: id }).strict(),
    z.object({ kind: z.literal('anonymous'), localId: key }).strict(),
  ]),
  eventTimeMs: timestamp, receivedAt: timestamp, sequence: positive, snapshotId: key,
  bodyHash: hash, text: z.string().max(65536).optional(),
  /** JSON projection generated by protocol helpers, never a raw network dump. */
  sanitizedEventJson: z.string().max(1_048_576).optional(),
  state: z.enum(['active', 'quarantined', 'forgotten']),
}).strict();
export type MessageRecord = z.infer<typeof messageSchema>;

export const factSchema = z.object({
  content: z.string().min(1).max(8192), quote: z.string().min(1).max(16384),
  confidence: z.enum(['reported', 'corroborated', 'disputed', 'inferred', 'unknown']),
  inferred: z.boolean(),
  eventTime: z.object({
    expression: z.string().max(1024), start: eventTimestamp.optional(), end: eventTimestamp.optional(),
    precision: z.enum(['instant', 'day', 'month', 'year', 'unknown']), ambiguous: z.boolean(),
  }).strict(),
  entities: z.array(z.object({
    key, kind: z.enum(['qq', 'uncertain']), label: z.string().max(128), qqId: id.optional(),
  }).strict()).max(32),
  relations: z.array(z.object({ from: key, to: key, relation: z.string().max(128), inferred: z.boolean() }).strict()).max(32),
}).strict();
export type ExtractedFact = z.infer<typeof factSchema>;

export const taskSchema = z.object({
  taskId: key, kind: z.enum(['retain', 'experience', 'observation', 'mental-model']),
  bankKey: key, snapshotId: key, provenance: provenanceSchema,
  messageKey: key.optional(), segmentId: key.optional(), templateId: key.optional(), scopeKey: key.optional(),
  routeFingerprint: hash,
  state: z.enum(['pending', 'running', 'retry', 'done', 'dead-letter', 'cancelled']),
  stage: z.enum(['ingress_committed', 'raw_intent', 'raw_text_saved', 'raw_active', 'extracted_validated',
    'fact_versions_written', 'facts_active', 'derived_jobs_enqueued', 'done']),
  retryCount: count, nextRunAt: timestamp,
  leaseToken: count.default(0), attemptCount: count.default(0), attemptCalls: count.default(0),
  ownerId: key.optional(), fence: count.optional(), leaseUntil: timestamp.optional(),
  checkpoint: z.object({ facts: z.array(factSchema).max(32).optional(), memoryIds: z.array(key).max(128).optional(),
    dirtyRecorded: z.boolean().optional(),
    derived: z.object({ text: z.string().min(1).max(131072), memoryId: key, operationKey: key,
      inputBankRevision: count, coveredRevision: count }).strict().optional(),
  }).strict(),
  calls: count, reservedTokens: count,
  failureCodes: z.array(key).max(100),
}).strict();
export type TaskRecord = z.infer<typeof taskSchema>;

export const bankSchema = z.object({
  bankKey: key, botId: id, personalityId: key, provisionMarker: key,
  baseId: key.optional(), state: z.enum(['unmapped', 'provisioning', 'ready', 'reconciliation_required', 'suspended', 'blocked', 'retiring']),
  revision: count, generation: count,
}).strict();
export type BankRecord = z.infer<typeof bankSchema>;

export const memorySchema = z.object({
  memoryId: key, version: positive, botId: id, personalityId: key, bankKey: key,
  kind: z.enum(['raw', 'world', 'experience', 'observation', 'mental-model']),
  provenance: provenanceSchema,
  contentHash: hash, writeIntentId: key,
  state: z.enum(['planned', 'writing', 'text_saved', 'active', 'superseded', 'invalidated', 'cleanup_pending', 'cleaned', 'reconcile_required', 'failed']),
  vectorState: z.enum(['not_requested', 'pending', 'ready', 'failed', 'unknown']),
  docId: key.optional(), text: z.string().max(131072).optional(),
  active: z.boolean(), tombstoned: z.boolean(), stale: z.boolean(),
  createdAt: timestamp, eventStart: eventTimestamp.optional(), eventEnd: eventTimestamp.optional(),
  supersedes: dependencySchema.optional(), templateId: key.optional(), coveredRevision: count.optional(),
  entities: z.array(key).max(128), scopeKey: key.optional(), generatedAt: timestamp.optional(),
}).strict();
export type MemoryVersion = z.infer<typeof memorySchema>;

export const intentSchema = z.object({
  intentId: key, bankKey: key, memoryId: key, version: positive,
  marker: key, contentHash: hash, provenance: provenanceSchema,
  ownerFence: positive,
  expectedBankRevision: count.optional(), expectedActiveVersion: positive.optional(), expectedNoActive: z.boolean().optional(),
  state: z.enum(['planned', 'writing', 'text_saved', 'reconcile_required', 'active', 'invalidated', 'cleaned', 'failed']),
  externalWrite: z.enum(['not_started', 'in_flight', 'settled', 'unknown']),
  text: z.string().max(131072).optional(), docIds: z.array(key).max(100),
  createdAt: timestamp, lastErrorCode: key.optional(),
}).strict();
export type WriteIntent = z.infer<typeof intentSchema>;

export const replySchema = z.object({
  replyId: key, messageKey: key, snapshotId: key, bankKey: key,
  configRevision: key, authEpoch: count, bindingRevision: count,
  provenance: provenanceSchema, deadlineAt: timestamp,
  state: z.enum(['pending', 'generating', 'prepared', 'sending', 'completed', 'partial', 'unknown', 'failed', 'cancelled']),
  outputHash: hash.optional(), cancellationCode: key.optional(), stageErrors: z.array(key).max(100).optional(),
}).strict();
export type ReplyRecord = z.infer<typeof replySchema>;

export const segmentSchema = z.object({
  segmentId: key, replyId: key, index: count, provenance: provenanceSchema,
  bodyHash: hash, text: z.string().max(65536).optional(),
  state: z.enum(['prepared', 'sending', 'succeeded', 'failed', 'unknown', 'cancelled']),
  echo: key.optional(), connectionEpoch: key.optional(), qqMessageId: key.optional(),
  errorCode: key.optional(), experienceTaskId: key.optional(),
}).strict();
export type SegmentRecord = z.infer<typeof segmentSchema>;

export const forgetTargetSchema = z.discriminatedUnion('kind', [
  z.object({ kind: z.literal('source'), sourceId: key, throughEpoch: positive }).strict(),
  z.object({ kind: z.literal('messages'), messageKeys: z.array(key).min(1).max(100000) }).strict(),
]);
export type ForgetTarget = z.infer<typeof forgetTargetSchema>;
export const ledgerEntrySchema = z.object({
  sequence: positive, operationId: key, previousHash: hash, entryHash: hash,
  target: forgetTargetSchema, action: z.enum(['forget', 'revoke']), at: timestamp,
}).strict();
export type LedgerEntry = z.infer<typeof ledgerEntrySchema>;
export const ledgerSchema = z.object({
  schemaVersion: z.literal(1), sequence: count, headHash: hash, entries: z.array(ledgerEntrySchema),
}).strict();
export type DeletionLedger = z.infer<typeof ledgerSchema>;
export const ZERO_HASH = '0'.repeat(64);
export function emptyLedger(): DeletionLedger { return { schemaVersion: 1, sequence: 0, headHash: ZERO_HASH, entries: [] }; }

export const forgetTaskSchema = z.object({
  operationId: key, target: forgetTargetSchema, ledgerSequence: positive,
  state: z.enum(['blocked', 'purging', 'retry', 'purged', 'dead-letter']),
  externalWriteUnknown: z.boolean(), retries: count, nextRunAt: timestamp,
  docIdsPending: z.array(key), errorCodes: z.array(key),
  purgeProof: z.object({ ledgerSequence: positive, allBanksEnumerated: z.literal(true), enumeratedAt: timestamp }).strict().optional(),
}).strict();
export type ForgetTask = z.infer<typeof forgetTaskSchema>;
const refreshSchema = z.object({
  key, bankKey: key, sourceId: key, templateId: key, routeFingerprint: hash, snapshotId: key,
  dirtyRevision: count, coveredRevision: count, firstDirtyAt: timestamp, nextRunAt: timestamp,
  scopeKey: key.optional(), provenance: provenanceSchema.optional(), pendingTaskId: key.optional(),
}).strict();
/** Last external repair attempt only. Never stores content, output or provider details. */
export const maintenanceMutationSchema = z.object({
  attemptId: key, generation: positive, memoryId: key, version: positive, docId: key,
  contentHash: hash, provenance: provenanceSchema, ownerFence: positive,
  externalWrite: z.enum(['not_started', 'in_flight', 'settled', 'unknown']),
  outcome: z.enum(['fulfilled', 'rejected']).optional(),
  startedAt: timestamp, settledAt: timestamp.optional(),
}).strict();
export type MaintenanceMutation = z.infer<typeof maintenanceMutationSchema>;
const maintenanceSchema = z.object({
  taskId: key, kind: z.enum(['cleanup', 'orphan', 'embedding', 'reconcile']), bankKey: key,
  docIds: z.array(key), intentId: key.optional(),
  state: z.enum(['pending', 'running', 'retry', 'done', 'dead-letter']),
  retries: count, nextRunAt: timestamp, errorCodes: z.array(key),
  mutation: maintenanceMutationSchema.optional(),
}).strict();
export type MaintenanceTask = z.infer<typeof maintenanceSchema>;

export const controlSchema = z.object({
  schemaVersion: z.literal(1), revision: count,
  ownerId: z.string(), ownerFence: count, ownerActive: z.boolean(),
  authEpoch: count, bindingRevision: count, configRevision: z.string(),
  ledgerSequence: count, ledgerHeadHash: hash,
  nextMessageSequence: positive,
  sources: z.record(key, sourceSchema),
  ingressConflicts: z.record(key, z.object({
    count: positive, firstSeenAt: timestamp, lastSeenAt: timestamp, bodyHashes: z.array(hash).min(1).max(8),
  }).strict()).default({}),
  messages: z.record(key, messageSchema),
  snapshots: z.record(key, snapshotSchema),
  tasks: z.record(key, taskSchema), banks: z.record(key, bankSchema),
  memories: z.record(key, memorySchema), activeMemory: z.record(key, key),
  intents: z.record(key, intentSchema), replies: z.record(key, replySchema), segments: z.record(key, segmentSchema),
  forgottenMessages: z.record(key, positive), forgottenSources: z.record(key, positive),
  forgetTasks: z.record(key, forgetTaskSchema), refresh: z.record(key, refreshSchema),
  maintenance: z.record(key, maintenanceSchema),
  pausedBanks: z.record(key, key),
}).strict();
export type ControlState = z.infer<typeof controlSchema>;
export function emptyControlState(): ControlState {
  return {
    schemaVersion: 1, revision: 0, ownerId: '', ownerFence: 0, ownerActive: false,
    authEpoch: 0, bindingRevision: 0, configRevision: '', ledgerSequence: 0, ledgerHeadHash: ZERO_HASH,
    nextMessageSequence: 1, sources: {}, ingressConflicts: {}, messages: {}, snapshots: {}, tasks: {}, banks: {},
    memories: {}, activeMemory: {}, intents: {}, replies: {}, segments: {},
    forgottenMessages: {}, forgottenSources: {}, forgetTasks: {}, refresh: {}, maintenance: {}, pausedBanks: {},
  };
}

export function memoryVersionKey(memoryId: string, version: number): string { return JSON.stringify([memoryId, version]); }
